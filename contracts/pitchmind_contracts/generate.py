"""Generate JSON Schemas and TypeScript types from the Pydantic contracts.

Usage (from the repo root):
    python -m pitchmind_contracts.generate

Writes:
    contracts/schemas/<Model>.json   one schema per wire model
    contracts/schemas/all.json       every model under $defs
    contracts/ts/index.ts            TypeScript types for the frontend (needs Node/npx)
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from . import models

CONTRACTS_DIR = Path(__file__).resolve().parent.parent
SCHEMAS_DIR = CONTRACTS_DIR / "schemas"
TS_DIR = CONTRACTS_DIR / "ts"

WIRE_MODELS: list[type[BaseModel]] = [
    models.MatchMeta,
    models.MatchEvent,
    models.StatSnapshot,
    models.Moment,
    models.Insight,
    models.Overlay,
]
EXTRA_MODELS: list[type[BaseModel]] = [models.FanProfile, models.Segment]

JSON2TS = "json-schema-to-typescript@15.0.4"


def _write_json(path: Path, data: object) -> None:
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def write_schemas() -> Path:
    SCHEMAS_DIR.mkdir(parents=True, exist_ok=True)
    for model in [*WIRE_MODELS, *EXTRA_MODELS]:
        _write_json(SCHEMAS_DIR / f"{model.__name__}.json", model.model_json_schema(mode="serialization"))

    _, combined = models_json_schema(
        [(m, "serialization") for m in [*WIRE_MODELS, *EXTRA_MODELS]],
        title="PitchMindContracts",
    )
    combined["$comment"] = f"Generated from pitchmind_contracts, schema_version {models.SCHEMA_VERSION}"
    all_path = SCHEMAS_DIR / "all.json"
    _write_json(all_path, combined)
    return all_path


def _strip_titles(node: object, *, keep: bool = True) -> object:
    """Drop property/item titles so json2ts inlines types instead of emitting `Id1`, `Msg4`, ..."""
    if isinstance(node, dict):
        return {
            k: _strip_titles(v, keep=k == "$defs")
            for k, v in node.items()
            if not (k == "title" and not keep and isinstance(v, str))
        }
    if isinstance(node, list):
        return [_strip_titles(v, keep=False) for v in node]
    return node


def write_typescript(all_schema: Path) -> bool:
    npx = shutil.which("npx")
    if npx is None:
        print("npx not found: skipped TypeScript generation", file=sys.stderr)
        return False

    TS_DIR.mkdir(parents=True, exist_ok=True)
    out = TS_DIR / "index.ts"
    schema = json.loads(all_schema.read_text(encoding="utf-8"))
    # Model definitions keep their titles (they become interface names); everything else loses them.
    defs = {name: {**_strip_titles(d, keep=False), "title": name} for name, d in schema["$defs"].items()}
    ts_input = TS_DIR / ".json2ts-input.json"
    _write_json(ts_input, {"title": "PitchMindContracts", "$defs": defs})
    subprocess.run(
        [npx, "--yes", JSON2TS, "--input", str(ts_input), "--output", str(out),
         "--unreachableDefinitions", "--additionalProperties", "false",
         "--bannerComment", ""],
        check=True,
    )
    ts_input.unlink()
    union = " | ".join(m.__name__ for m in WIRE_MODELS)
    header = (
        "/* Generated by `python -m pitchmind_contracts.generate`. Do not edit by hand. */\n"
        f"export const SCHEMA_VERSION = \"{models.SCHEMA_VERSION}\";\n\n"
    )
    body = out.read_text(encoding="utf-8")
    footer = (
        "\n/** Any message arriving from Web PubSub or the API. Switch on `msg`. */\n"
        f"export type WireMessage = {union};\n"
    )
    out.write_text(header + body + footer, encoding="utf-8")
    return True


def main() -> None:
    all_schema = write_schemas()
    print(f"schemas -> {SCHEMAS_DIR}")
    if write_typescript(all_schema):
        print(f"types   -> {TS_DIR / 'index.ts'}")


if __name__ == "__main__":
    main()
