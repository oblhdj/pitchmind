"""Assemble and run the whole pipeline in one process, or replay a recorded match."""

from __future__ import annotations

import asyncio
import logging
from collections.abc import Sequence
from dataclasses import dataclass, field
from pathlib import Path

from pitchmind_agents import AgentsConfig, AgentsService, AgentTeam, mock_client_set
from pitchmind_bus import InMemoryBus, Wire
from pitchmind_contracts import Insight, MatchEvent, Moment, Overlay, Segment, StatSnapshot, parse_wire
from pitchmind_render import LEAD_S, OverlayRenderer
from pitchmind_simulator import SCENARIOS, build_match_meta

from .gateway import Gateway
from .stages import agents_stage, moments_stage, render_stage, simulator_stage, stats_stage

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class PipelineConfig:
    segments: Sequence[Segment]
    scenario: str = "demo-comeback"
    seed: int = 7
    match_id: str = "M001"
    speed: float = 10.0
    llm: str = "mock"  # "mock" (offline) or "foundry"
    agents: AgentsConfig = field(default_factory=AgentsConfig)


def build_agents(config: PipelineConfig) -> AgentsService:
    if config.llm == "foundry":
        from pitchmind_agents.clients import foundry_client_set  # needs Azure login and FOUNDRY_* variables

        clients = foundry_client_set()
    else:
        clients = mock_client_set()
    return AgentsService(AgentTeam(clients, config.agents), config.segments)


class Pipeline:
    """Simulator -> stats -> moments -> agents -> render -> gateway, all on one in-memory bus."""

    def __init__(self, config: PipelineConfig, gateway: Gateway, *, bus: InMemoryBus | None = None) -> None:
        self.config = config
        self.gateway = gateway
        self.bus = bus or InMemoryBus()
        self._consumers: list[asyncio.Task[None]] = []

    def start(self) -> None:
        """Start every consumer. They subscribe synchronously, before the first event exists."""
        stages = [
            stats_stage(self.bus),
            moments_stage(self.bus),
            agents_stage(self.bus, build_agents(self.config)),
            render_stage(self.bus, OverlayRenderer(self.config.segments)),
            self.gateway.run(self.bus),
        ]
        self._consumers = [asyncio.create_task(stage) for stage in stages]

    async def play(self) -> None:
        """Play the match at the configured speed. Returns when the final whistle is published."""
        meta = build_match_meta(self.config.match_id, seed=self.config.seed)
        scenario = SCENARIOS[self.config.scenario]
        await simulator_stage(self.bus, meta, scenario, self.config.seed, self.config.speed)

    async def drain(self, *, idle_s: float = 0.3, timeout_s: float = 60.0) -> None:
        """Wait until no stage has work left: nothing queued and nothing being handled for ``idle_s``.

        "Being handled" matters with real models: an agent can work on the last moment (the
        full-time recap) for seconds after every queue is empty.
        """
        loop = asyncio.get_running_loop()
        deadline = loop.time() + timeout_s
        quiet_since: float | None = None
        while loop.time() < deadline:
            if self.bus.busy() == 0:
                quiet_since = quiet_since or loop.time()
                if loop.time() - quiet_since >= idle_s:
                    return
            else:
                quiet_since = None
            await asyncio.sleep(0.02)
        raise TimeoutError(f"pipeline still busy after {timeout_s}s ({self.bus.busy()} messages queued or in flight)")

    async def stop(self) -> None:
        await self.bus.close()
        await asyncio.gather(*self._consumers, return_exceptions=True)


def message_time(message: Wire) -> float:
    """When a message happened, in match time (overlays: when they were rendered)."""
    if isinstance(message, MatchEvent | StatSnapshot | Moment | Insight):
        return message.t
    if isinstance(message, Overlay):
        return max(0.0, message.show_at - LEAD_S)
    return 0.0


def read_recording(path: Path) -> list[Wire]:
    with path.open(encoding="utf-8") as f:
        return [parse_wire(line) for line in f if line.strip()]


async def replay_recording(messages: Sequence[Wire], gateway: Gateway, speed: float) -> None:
    """Feed a recorded match to the gateway, paced by match time (``speed`` 0 = instantly).

    Recorded order is kept: insights generated by slow real models appear in the order
    they were produced, at the pace of the match.
    """
    loop = asyncio.get_running_loop()
    started = loop.time()
    clock = 0.0
    for message in messages:
        clock = max(clock, message_time(message))
        if speed > 0:
            await asyncio.sleep(max(0.0, started + clock / speed - loop.time()))
        else:
            await asyncio.sleep(0)
        gateway.observe(message)
