"""The schema/TypeScript generator, and a drift check: committed schemas match the models."""

import json
import subprocess
from pathlib import Path
from typing import Any

import pytest
from pitchmind_contracts import generate

COMMITTED = Path(__file__).resolve().parents[1] / "schemas"


def test_committed_schemas_match_the_models(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    monkeypatch.setattr(generate, "SCHEMAS_DIR", tmp_path)
    generate.write_schemas()
    fresh = sorted(p.name for p in tmp_path.glob("*.json"))
    assert fresh == sorted(p.name for p in COMMITTED.glob("*.json"))
    for name in fresh:
        assert json.loads((tmp_path / name).read_text(encoding="utf-8")) == json.loads(
            (COMMITTED / name).read_text(encoding="utf-8")
        ), f"{name} is stale: run python -m pitchmind_contracts.generate"


def test_every_title_is_stripped_so_json2ts_inlines_types() -> None:
    schema = {"$defs": {"A": {"title": "A", "properties": {"x": {"title": "X", "type": "string"}}}}}
    stripped = generate._strip_titles(schema)
    assert stripped == {"$defs": {"A": {"properties": {"x": {"type": "string"}}}}}  # names are re-added later


def test_typescript_is_skipped_without_npx(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    monkeypatch.setattr("shutil.which", lambda _: None)
    assert generate.write_typescript(tmp_path / "all.json") is False


def test_typescript_gets_version_header_and_wire_union(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    monkeypatch.setattr(generate, "SCHEMAS_DIR", tmp_path / "schemas")
    monkeypatch.setattr(generate, "TS_DIR", tmp_path / "ts")
    monkeypatch.setattr("shutil.which", lambda _: "npx")

    def fake_json2ts(cmd: list[str], **_: Any) -> subprocess.CompletedProcess[str]:
        Path(cmd[cmd.index("--output") + 1]).write_text("export interface MatchMeta {}\n", encoding="utf-8")
        return subprocess.CompletedProcess(cmd, 0)

    monkeypatch.setattr("subprocess.run", fake_json2ts)
    generate.main()
    ts = (tmp_path / "ts" / "index.ts").read_text(encoding="utf-8")
    assert ts.startswith("/* Generated by")
    assert "export interface MatchMeta {}" in ts
    assert "export type WireMessage = MatchMeta | MatchEvent | StatSnapshot | Moment | Insight | Overlay;" in ts
    assert not (tmp_path / "ts" / ".json2ts-input.json").exists()
